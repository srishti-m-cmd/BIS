// ─── EXTRACTED ATTRIBUTES TEMPLATES ───────────────────────────────────────────
export const extractAttributes = (description) => {
  const lowerDesc = description.toLowerCase();
  const attributes = {};

  // Capacity extraction
  const capacityMatch = description.match(/(\d+)\s*(L|litre|liter|litres|liters)/i);
  if (capacityMatch) attributes.capacity = `${capacityMatch[1]} L`;

  // Voltage extraction
  const voltageMatch = description.match(/(\d+[\-–]\d+\s*[Vv]|(\d+)\s*[Vv]olt)/i);
  if (voltageMatch) attributes.voltage = voltageMatch[0];

  // Use classification
  if (lowerDesc.includes('domestic') || lowerDesc.includes('home') || lowerDesc.includes('household')) {
    attributes.intendedUse = 'Domestic';
  } else if (lowerDesc.includes('commercial') || lowerDesc.includes('industrial')) {
    attributes.intendedUse = 'Commercial/Industrial';
  }

  // Wattage
  const wattMatch = description.match(/(\d+)\s*(W|watt|watts)/i);
  if (wattMatch) attributes.power = `${wattMatch[1]} W`;

  return attributes;
};
